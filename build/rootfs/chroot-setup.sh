#!/bin/bash
# Runs INSIDE the aarch64 rootfs (systemd-nspawn + qemu-user binfmt). Not meant to be run on the host.
set -euxo pipefail
cd /
# build-time pacman tweaks: no landlock sandbox/CheckSpace under qemu-user + non-mountpoint root
sed -i 's/^CheckSpace/#CheckSpace/' /etc/pacman.conf
grep -q '^DisableSandbox' /etc/pacman.conf || sed -i '/^\[options\]/a DisableSandbox' /etc/pacman.conf
sed -i 's/^#\?IgnorePkg.*/IgnorePkg = linux-aarch64 linux-aarch64-headers/' /etc/pacman.conf
grep -q '^IgnorePkg' /etc/pacman.conf || sed -i '/^\[options\]/a IgnorePkg = linux-aarch64 linux-aarch64-headers' /etc/pacman.conf
pacman-key --init
pacman-key --populate archlinux archlinuxarm
# drop what we do not use: generic kernel, all linux-firmware (vendor blobs come off the eMMC), editors/netctl/etc
DROP=()
for p in linux-aarch64 linux-firmware linux-firmware-atheros linux-firmware-cirrus linux-firmware-amdgpu linux-firmware-other \
         linux-firmware-radeon linux-firmware-mediatek linux-firmware-intel linux-firmware-broadcom linux-firmware-nvidia \
         linux-firmware-realtek linux-firmware-whence vim vim-runtime netctl gpm mkinitcpio mkinitcpio-busybox pciutils \
         net-tools dhcpcd; do
  pacman -Qq "$p" >/dev/null 2>&1 && DROP+=("$p")
done
((${#DROP[@]})) && pacman -Rdd --noconfirm "${DROP[@]}"
pacman -Syu --noconfirm --needed iwd cpio wireless-regdb
rm -rf /var/cache/pacman/pkg/* /var/lib/pacman/sync/*
# services
systemctl enable sshd.service iwd.service systemd-networkd.service systemd-resolved.service systemd-timesyncd.service \
  rotate-firstboot.service rotate-resize.service rotate-keyring.service "serial-getty@ttyGS0.service"
# private keyring generated at build must not ship: rotate-keyring.service recreates it on the device
rm -rf /etc/pacman.d/gnupg
# no machine identity baked in
: > /etc/machine-id
rm -f /etc/ssh/ssh_host_*   # regenerated by sshd-keygen on first start
echo 'rotate' > /etc/hostname
# resolv.conf -> resolved stub
ln -sf /run/systemd/resolve/stub-resolv.conf /etc/resolv.conf
