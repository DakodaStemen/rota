LaunchSpec build_launch(const Config& cfg, const SystemDef& sys, const Game& game) {
  LaunchSpec s;
  s.append_config_path = cfg.state_dir + "/retroarch-rotate.cfg";
  std::ostringstream c;
  c << "# generated by rotate-frontend; do not edit\n";
  c << "network_cmd_enable = \"true\"\n";
  c << "network_cmd_port = \"" << cfg.cmd_port << "\"\n";
  c << "config_save_on_exit = \"false\"\n";
  if (cfg.resume_on_wake) {
    c << "savestate_auto_save = \"true\"\n";
    c << "savestate_auto_load = \"true\"\n";
  }
  s.append_config_text = c.str();
  s.argv = {cfg.retroarch_bin, "-L", cfg.core_path(sys), "--appendconfig", s.append_config_path};
  if (!cfg.retroarch_cfg.empty()) {
    s.argv.push_back("--config");
    s.argv.push_back(cfg.retroarch_cfg);
  }
  s.argv.push_back(game.path);
  return s;
}

bool prepare_launch(const LaunchSpec& spec) {
  auto slash = spec.append_config_path.rfind('/');
  if (slash != std::string::npos) make_dirs(spec.append_config_path.substr(0, slash));
  return write_file(spec.append_config_path, spec.append_config_text);
}

pid_t spawn(const LaunchSpec& spec) {
  pid_t pid = fork();
  if (pid != 0) return pid;
  std::vector<char*> av;
  for (const auto& a : spec.argv) av.push_back(const_cast<char*>(a.c_str()));
  av.push_back(nullptr);
  execvp(av[0], av.data());
  _exit(127);
}

int wait_child(pid_t pid) {
  int st = 0;
  while (waitpid(pid, &st, 0) < 0) {
    if (errno != EINTR) return -1;
  }
  if (WIFEXITED(st)) return WEXITSTATUS(st);
  if (WIFSIGNALED(st)) return 128 + WTERMSIG(st);
  return -1;
}

// ---- RetroArchCtl ------------------------------------------------------------
bool RetroArchCtl::send(const std::string& cmd) {
  int fd = socket(AF_INET, SOCK_DGRAM | SOCK_CLOEXEC, 0);
  if (fd < 0) return false;
  sockaddr_in a{};
  a.sin_family = AF_INET;
  a.sin_port = htons(static_cast<uint16_t>(port_));
  inet_pton(AF_INET, host_.c_str(), &a.sin_addr);
  ssize_t n = sendto(fd, cmd.data(), cmd.size(), 0, reinterpret_cast<sockaddr*>(&a), sizeof a);
  close(fd);
  return n == static_cast<ssize_t>(cmd.size());
}

std::string RetroArchCtl::query_status() {
  int fd = socket(AF_INET, SOCK_DGRAM | SOCK_CLOEXEC, 0);
  if (fd < 0) return "";
  sockaddr_in a{};
  a.sin_family = AF_INET;
  a.sin_port = htons(static_cast<uint16_t>(port_));
  inet_pton(AF_INET, host_.c_str(), &a.sin_addr);
  std::string cmd = "GET_STATUS";
  std::string reply;
  if (sendto(fd, cmd.data(), cmd.size(), 0, reinterpret_cast<sockaddr*>(&a), sizeof a) > 0) {
    struct pollfd p = {fd, POLLIN, 0};
    if (poll(&p, 1, timeout_ms_) > 0) {
      char buf[512];
      ssize_t n = recv(fd, buf, sizeof buf - 1, 0);
      if (n > 0) reply.assign(buf, static_cast<size_t>(n));
    }
  }
  close(fd);
  return trim(reply);
}

RetroArchCtl::Method RetroArchCtl::pause(pid_t pid) {
  std::string st = query_status();
  if (st.rfind("GET_STATUS PAUSED", 0) == 0) {
    method_ = Method::AlreadyPaused;
  } else if (st.rfind("GET_STATUS PLAYING", 0) == 0) {
    method_ = send("PAUSE_TOGGLE") ? Method::Net : Method::None;
  } else if (pid > 0) {
    method_ = kill(pid, SIGSTOP) == 0 ? Method::Signal : Method::None;
  } else {
    method_ = send("PAUSE_TOGGLE") ? Method::Net : Method::None;
  }
  return method_;
}

bool RetroArchCtl::resume(pid_t pid) {
  bool ok = true;
  switch (method_) {
    case Method::Net: ok = send("PAUSE_TOGGLE"); break;
    case Method::Signal: ok = pid > 0 && kill(pid, SIGCONT) == 0; break;
    default: break;
  }
  method_ = Method::None;
  return ok;
}

bool RetroArchCtl::save_state() { return send("SAVE_STATE"); }

